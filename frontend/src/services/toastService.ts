// Simple toast service to display messages to the user
import { toast } from 'react-toastify';

export const showSuccessToast = (message: string): void => {
  toast.success(message, {
    position: "top-right",
    autoClose: 3000,
    hideProgressBar: false,
    closeOnClick: true,
    pauseOnHover: true,
    draggable: true
  });
};

